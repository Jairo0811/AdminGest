/**
 * Minimal toolkit to build printable HTML safely.
 *
 * Printable documents are written into a window that shares the AdminGest origin, so an
 * unescaped value (a task title, a customer name…) would run with the user's session.
 * Every interpolation in the {@link html} template is escaped unless it is already a
 * {@link SafeHtml} produced by this module. Content from users can therefore never be
 * promoted to markup by accident: functions that print require SafeHtml, not strings.
 */
const HTML_ESCAPES: Record<string, string> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
  '`': '&#96;',
};

export function escapeHtml(value: unknown): string {
  return String(value ?? '').replace(/[&<>"'`]/g, (character) => HTML_ESCAPES[character]);
}

export class SafeHtml {
  constructor(private readonly value: string) {}
  toString(): string {
    return this.value;
  }
}

type HtmlValue = SafeHtml | string | number | boolean | null | undefined | HtmlValue[];

const render = (value: HtmlValue): string => {
  if (value instanceof SafeHtml) return value.toString();
  if (Array.isArray(value)) return value.map(render).join('');
  if (value === null || value === undefined || value === false) return '';
  return escapeHtml(value);
};

/** Tagged template: `html\`<td>${userValue}</td>\`` escapes `userValue`. */
export function html(strings: TemplateStringsArray, ...values: HtmlValue[]): SafeHtml {
  return new SafeHtml(
    strings.reduce(
      (result, part, index) => result + part + (index < values.length ? render(values[index]) : ''),
      '',
    ),
  );
}

/** Joins fragments that are already safe. */
export const joinHtml = (fragments: SafeHtml[], separator = ''): SafeHtml =>
  new SafeHtml(fragments.map(String).join(escapeHtml(separator)));

/**
 * Accepts only image sources the print window is allowed to load: same-origin assets,
 * HTTPS images and PNG/JPEG/SVG data URLs generated by the application (QR codes).
 */
export function safeImageSource(value: string, origin = window.location.origin): string {
  if (/^data:image\/(png|jpeg|svg\+xml);base64,[a-z0-9+/=]+$/i.test(value)) return value;
  try {
    const url = new URL(value, origin);
    if (url.origin === origin || url.protocol === 'https:') return url.href;
  } catch {
    // Falls through to the empty image below.
  }
  return '';
}

/** Restricts CSS values interpolated into style attributes (widths, colors). */
export const cssPercent = (value: number): string =>
  `${Math.min(100, Math.max(0, Number.isFinite(value) ? value : 0)).toFixed(2)}%`;

export function createNonce(): string {
  const bytes = new Uint8Array(16);
  crypto.getRandomValues(bytes);
  return Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('');
}

/**
 * Content-Security-Policy of printable windows: no network access (connect/form/frames),
 * no inline handlers and only the nonce-bearing script that triggers printing. Even if a
 * value escaped this module, it could not execute nor exfiltrate the session.
 */
export function printContentSecurityPolicy(nonce: string, origin = window.location.origin): string {
  return [
    "default-src 'none'",
    `img-src ${origin} https: data:`,
    "style-src 'unsafe-inline'",
    `script-src 'nonce-${nonce}'`,
    "base-uri 'none'",
    "form-action 'none'",
  ].join('; ');
}
